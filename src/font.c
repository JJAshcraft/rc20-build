static unsigned char glyphs[128][7];
static int ready;

static void build(void)
{
    static const unsigned char box[7] = {0x1F, 0x11, 0x11, 0x11, 0x11, 0x11, 0x1F};
    for (int c = 0; c < 128; c++) memcpy(glyphs[c], box, 7);
    for (size_t i = 0; i < sizeof src / sizeof src[0]; i++) {
        int c = (unsigned char)src[i][0][0];
        for (int r = 0; r < 7; r++) {
            unsigned char m = 0;
            for (int x = 0; x < 5; x++)
                if (src[i][r + 1][x] == '#') m |= (unsigned char)(0x10 >> x);
            glyphs[c][r] = m;
        }
    }
    ready = 1;
}

const unsigned char *font_glyph(int c)
{
    if (!ready) build();
    if (c >= 'a' && c <= 'z') c -= 32;
    if (c < 0 || c > 127) c = 127;
    return glyphs[c];
}
